"""The declared parameters of every public analysis function.

Data for :mod:`petrophys.function_schema`: what each parameter takes, by
kind (see that module). Reviewed against each function's code; checked against
the signatures by :func:`petrophys.function_schema.check`. Add an entry when a
public function is added to :mod:`petrophys.interpretation`,
:mod:`petrophys.evaluation`,
:mod:`petrophys.preprocessing` or :mod:`petrophys.visualization`.
"""

from typing import Dict, Optional

from petrophys.function_schema import FunctionDeclaration, ParameterDeclaration

__all__ = ["DECLARATIONS"]


def fn(
    samplewise: bool = False, **parameters: ParameterDeclaration
) -> FunctionDeclaration:
    return FunctionDeclaration(dict(parameters), samplewise)


def curve(
    name: Optional[str] = None, unit: Optional[str] = None
) -> ParameterDeclaration:
    return ParameterDeclaration("curve", curve=name, unit=unit)


def curve_name(name: Optional[str] = None, many: bool = False) -> ParameterDeclaration:
    return ParameterDeclaration("curve_name", curve=name, many=many)


def value(
    unit: Optional[str] = None, curve: Optional[str] = None
) -> ParameterDeclaration:
    return ParameterDeclaration("value", curve=curve, unit=unit)


def values(unit: Optional[str] = None) -> ParameterDeclaration:
    return ParameterDeclaration("values", unit=unit)


def choice(*options: str, many: bool = False) -> ParameterDeclaration:
    return ParameterDeclaration("choice", choices=tuple(options), many=many)


def lithology(*options: str, many: bool = False) -> ParameterDeclaration:
    """A choice of the rock's lithology or matrix (role ``lithology``): a caller may fill it per sample from the
    interpreted lithology."""
    return ParameterDeclaration("choice", choices=tuple(options), many=many, role="lithology")


def window(role: str) -> ParameterDeclaration:
    return ParameterDeclaration("window", role=role)


def switch() -> ParameterDeclaration:
    return ParameterDeclaration("switch")


def per_zone() -> ParameterDeclaration:
    return ParameterDeclaration("per_zone")


def mask() -> ParameterDeclaration:
    return ParameterDeclaration("mask")


def depth() -> ParameterDeclaration:
    return ParameterDeclaration("depth")


def well() -> ParameterDeclaration:
    return ParameterDeclaration("well")


def text(many: bool = False) -> ParameterDeclaration:
    return ParameterDeclaration("text", many=many)


def object_() -> ParameterDeclaration:
    return ParameterDeclaration("object")


